// Builds dist/css/tokens.css (all layers, all axis values, one file)
// and dist/json/tokens.json (metadata used by the Storybook docs).
//
// Each axis value gets its own selector, and references are kept as
// var(--...) so brand and mode can be switched independently at runtime:
//
//   :root                  primitives + semantic
//   [data-brand="brand-y"] palette.* and brand.* for that brand
//   [data-mode="dark"]     color.* for that mode, pointing at var(--palette-*)
import StyleDictionary from 'style-dictionary';
import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import {
  PRIMITIVES, SEMANTIC, BRANDS, MODES, DEFAULT_BRAND, DEFAULT_MODE, nameOf,
} from './layers.mjs';

const TMP = 'dist/.tmp';
const transforms = ['attribute/cti', 'name/kebab', 'color/css', 'fontFamily/css'];

rmSync('dist', { recursive: true, force: true });
mkdirSync('dist/css', { recursive: true });
mkdirSync('dist/json', { recursive: true });

const inFiles = (files) => (token) => files.some((f) => token.filePath.endsWith(f));

// `:where()` keeps the default at zero specificity, so an explicit
// data attribute always wins regardless of order in the file.
const selectorFor = (axis, file, defaultFile) => {
  const attr = `[data-${axis}="${nameOf(file)}"]`;
  return file === defaultFile ? `:where(:root), ${attr}` : attr;
};

async function build({ id, source, include, selector, layer }) {
  const sd = new StyleDictionary({
    source,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      css: {
        transforms,
        buildPath: `${TMP}/`,
        files: [
          {
            destination: `${id}.css`,
            format: 'css/variables',
            filter: inFiles(include),
            options: { selector, outputReferences: true, showFileHeader: false },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
  const { allTokens } = await sd.getPlatformTokens('css');
  const docs = allTokens.filter(inFiles(include)).map((t) => ({
    name: t.path.join('.'),
    cssVar: `--${t.name}`,
    type: t.$type,
    layer,
    source: nameOf(t.filePath),
    reference: typeof t.original.$value === 'string' && t.original.$value.startsWith('{')
      ? t.original.$value.slice(1, -1)
      : null,
    value: t.$value,
  }));
  return { css: readFileSync(`${TMP}/${id}.css`, 'utf8'), docs };
}

const parts = [];
const docs = [];

// 1. Primitives + semantic: always on :root.
//    Semantic tokens reference brand.* so a brand is included for resolution.
const base = await build({
  id: 'primitives',
  source: [...PRIMITIVES],
  include: PRIMITIVES,
  selector: ':root',
  layer: 'primitives',
});
parts.push(['Primitives', base]);

const semantic = await build({
  id: 'semantic',
  source: [...PRIMITIVES, DEFAULT_BRAND, ...SEMANTIC],
  include: SEMANTIC,
  selector: ':root',
  layer: 'semantic',
});
parts.push(['Semantic', semantic]);

// 2. Brand axis: one block per brand file.
for (const brand of BRANDS) {
  const out = await build({
    id: `brand-${nameOf(brand)}`,
    source: [...PRIMITIVES, brand],
    include: [brand],
    selector: selectorFor('brand', brand, DEFAULT_BRAND),
    layer: 'brand',
  });
  parts.push([`Brand: ${nameOf(brand)}`, out]);
}

// 3. Mode axis: one block per mode file. Values point at var(--palette-*),
//    so they follow whichever brand is active.
for (const mode of MODES) {
  const out = await build({
    id: `mode-${nameOf(mode)}`,
    source: [...PRIMITIVES, DEFAULT_BRAND, mode],
    include: [mode],
    selector: selectorFor('mode', mode, DEFAULT_MODE),
    layer: 'mode',
  });
  parts.push([`Mode: ${nameOf(mode)}`, out]);
}

const header = `/**
 * Generated by scripts/build-tokens.mjs. Do not edit.
 * Set data-brand and data-mode on the same element (usually <html>).
 * Brands: ${BRANDS.map(nameOf).join(', ')} (default ${nameOf(DEFAULT_BRAND)})
 * Modes:  ${MODES.map(nameOf).join(', ')} (default ${nameOf(DEFAULT_MODE)})
 */\n`;

writeFileSync(
  'dist/css/tokens.css',
  header + parts.map(([label, p]) => `\n/* ${label} */\n${p.css.trim()}\n`).join(''),
);

// Docs metadata: every token from every file, tagged with layer and source,
// so the docs can show the reference chain for the active brand and mode.
for (const [, p] of parts) docs.push(...p.docs);
writeFileSync(
  'dist/json/tokens.json',
  JSON.stringify(
    {
      axes: { brand: BRANDS.map(nameOf), mode: MODES.map(nameOf) },
      defaults: { brand: nameOf(DEFAULT_BRAND), mode: nameOf(DEFAULT_MODE) },
      tokens: docs,
    },
    null,
    2,
  ),
);

rmSync(TMP, { recursive: true, force: true });
console.log(`Built ${docs.length} tokens -> dist/css/tokens.css, dist/json/tokens.json`);
